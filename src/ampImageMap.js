export function getAmpImage(rigText = "") {
  const normalized = rigText.toLowerCase();

  for (const profile of ampProfiles) {
    for (const alias of profile.aliases) {
      if (normalized.includes(alias.toLowerCase())) {
        return profile.image;
      }
    }
  }

  return "";
}